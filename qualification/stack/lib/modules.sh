# shellcheck shell=bash
# Writes the main server's policy module catalog, and what the driver needs to
# serve its remote module.
#
# Every instance is scoped `assigned`, so none applies to an account until a
# scenario assigns it, and every other scenario sees the server as it would
# without a catalog.
#
# The remote instance points at a module the Rust driver serves on the host. A
# plaintext module endpoint must be on loopback, and the host is not loopback
# from inside a container, so it is served over TLS with a certificate a per-run
# CA signs for host.docker.internal. The catalog trusts that CA and reads the
# bearer token through the file secrets backend, which is the path a deployment
# with a remote module takes.
#
# The remote instance starts disabled: an enabled instance that cannot be
# reached stops the server from starting, and the driver serves the module only
# while its scenario runs.

QUAL_MODULE_HOST="host.docker.internal"
QUAL_MODULE_TOKEN_SECRET="qual-remote-token"

qual_write_module_catalog() {
  local catalog_dir="$1" secrets_dir="$2" tls_dir="$3" port="$4"
  mkdir -p "${catalog_dir}" "${secrets_dir}" "${tls_dir}"
  chmod 700 "${secrets_dir}" "${tls_dir}"

  openssl req -x509 -newkey rsa:2048 -nodes -days 2 -subj "/CN=qualification module CA" \
    -keyout "${tls_dir}/ca-key.pem" -out "${catalog_dir}/module-ca.pem" >/dev/null 2>&1 || return 1
  openssl req -newkey rsa:2048 -nodes -subj "/CN=${QUAL_MODULE_HOST}" \
    -keyout "${tls_dir}/key.pem" -out "${tls_dir}/request.csr" >/dev/null 2>&1 || return 1
  printf 'subjectAltName=DNS:%s\nbasicConstraints=CA:FALSE\nextendedKeyUsage=serverAuth\n' \
    "${QUAL_MODULE_HOST}" > "${tls_dir}/extensions.cnf"
  openssl x509 -req -days 2 -in "${tls_dir}/request.csr" \
    -CA "${catalog_dir}/module-ca.pem" -CAkey "${tls_dir}/ca-key.pem" -CAcreateserial \
    -extfile "${tls_dir}/extensions.cnf" -out "${tls_dir}/cert.pem" >/dev/null 2>&1 || return 1
  rm -f "${tls_dir}/request.csr" "${tls_dir}/extensions.cnf" "${tls_dir}/ca-key.pem" \
    "${catalog_dir}/module-ca.srl" "${tls_dir}/module-ca.srl"

  qual_random_suffix > "${secrets_dir}/${QUAL_MODULE_TOKEN_SECRET}"
  cp "${secrets_dir}/${QUAL_MODULE_TOKEN_SECRET}" "${tls_dir}/token"
  chmod 600 "${secrets_dir}/${QUAL_MODULE_TOKEN_SECRET}" "${tls_dir}/token" "${tls_dir}/key.pem"

  cat > "${catalog_dir}/catalog.toml" <<TOML
# Generated by qualification/stack/lib/modules.sh for one run.

[[module]]
id = "qual-gate"
kind = "signer-policy"
scope = "assigned"
hooks = ["before_proposal_created", "before_transaction_approved"]
timeout_ms = 200
on_error = "deny"

[[module]]
id = "qual-cap"
kind = "spending-limit"
scope = "assigned"
hooks = ["before_proposal_created", "before_transaction_approved"]
timeout_ms = 200
on_error = "deny"
disclosure = "params"
description = "Qualification spending cap for the accounts a scenario assigns"

[[module]]
id = "qual-recipient"
kind = "recipient-policy"
scope = "assigned"
hooks = ["before_proposal_created", "before_transaction_approved"]
timeout_ms = 200
on_error = "deny"
disclosure = "params"
description = "Qualification recipient denylist for the accounts a scenario assigns"

[[module]]
id = "qual-switch"
kind = "signer-policy"
scope = "assigned"
hooks = ["before_proposal_created"]
timeout_ms = 200
on_error = "deny"
operator_can_disable = true

[[module]]
id = "qual-remote"
kind = "grpc"
endpoint = "grpc://${QUAL_MODULE_HOST}:${port}"
enabled = false
scope = "assigned"
hooks = ["before_proposal_created"]
timeout_ms = 500
on_error = "deny"
operator_can_disable = true
auth = { token_secret = "${QUAL_MODULE_TOKEN_SECRET}" }
tls = { ca_file = "module-ca.pem" }
TOML
}
